"""
Reads ablation results and prints a formatted comparison table with separate
averages for Replica and TUM, using tracking-thread FPS (1/mean tracking time).

Experiment list is loaded from cfg/triangle_mapper/experiments/manifest.json,
which is generated by scripts/generate_ablation_configs.py.

Usage: python3 eval/summarize_ablations.py [results_dir] [repo_root]
Defaults: results_dir=./results, repo_root=./
"""

import os
import sys
import csv
import glob
import json
import numpy as np

results_dir = sys.argv[1] if len(sys.argv) > 1 else "./results"
repo_root   = sys.argv[2] if len(sys.argv) > 2 else "."

manifest_path = os.path.join(repo_root, "cfg", "triangle_mapper", "experiments", "manifest.json")
if not os.path.exists(manifest_path):
    sys.exit(f"Manifest not found at {manifest_path}.\nRun: python3 scripts/generate_ablation_configs.py")

with open(manifest_path) as f:
    EXPERIMENTS = [
        (e["name"], e["label"])
        for g in json.load(f)["groups"]
        for e in g["experiments"]
    ]

# log.csv columns: scene T R PSNR SSIM LPIPS Time RenderFPS NumTriangles VRAM
COL_SCENE = 0
COL_T     = 1
COL_PSNR  = 3
COL_SSIM  = 4
COL_LPIPS = 5

# (key, header, width, higher_is_better)
METRICS = [
    ("psnr",  "PSNR↑",  6, True),
    ("ssim",  "SSIM↑",  6, True),
    ("lpips", "LPIPS↓", 6, False),
    ("ate",   "ATE↓",   7, False),
    ("fps",   "FPS↑",   6, True),
]

BOLD      = "\033[1m"
UNDERLINE = "\033[4m"
RESET     = "\033[0m"


def is_tum(scene):
    return "freiburg" in scene or "rgbd_dataset" in scene


def mean_of(values):
    floats = [float(v) for v in values if v not in (None, "None", "")]
    return np.mean(floats) if floats else float("nan")


def load_log_csv(path):
    rows = []
    with open(path, newline="") as f:
        reader = csv.reader(f)
        next(reader, None)
        for row in reader:
            if len(row) >= 6:
                rows.append(row)
    return rows


def tracking_fps(scene_dir):
    path = os.path.join(scene_dir, "TrackingTime.txt")
    if not os.path.exists(path):
        return float("nan")
    with open(path) as f:
        lines = f.readlines()
    times = []
    for line in (lines[:-3] if len(lines) > 3 else lines):
        try:
            times.append(float(line.strip()))
        except ValueError:
            pass
    return 1.0 / np.mean(times) if times else float("nan")


def find_scene_dirs(exp_dir):
    scene_dirs = {}
    for trial_dir in glob.glob(os.path.join(exp_dir, "*_rgbd_*")):
        for scene_path in glob.glob(os.path.join(trial_dir, "*")):
            if os.path.isdir(scene_path):
                scene_dirs[os.path.basename(scene_path)] = scene_path
    return scene_dirs


def compute_stats(rows, scene_dirs):
    fps_vals = [tracking_fps(scene_dirs[r[COL_SCENE]])
                for r in rows if r[COL_SCENE] in scene_dirs]
    return {
        "psnr":  mean_of([r[COL_PSNR]  for r in rows]),
        "ssim":  mean_of([r[COL_SSIM]  for r in rows]),
        "lpips": mean_of([r[COL_LPIPS] for r in rows]),
        "ate":   mean_of([r[COL_T]     for r in rows]),
        "fps":   float(np.nanmean(fps_vals)) if fps_vals else float("nan"),
    }


def rank_values(all_stats, key, higher_is_better):
    vals = [s[key] for s in all_stats if s is not None and not np.isnan(s[key])]
    if not vals:
        return float("nan"), float("nan")
    vals_sorted = sorted(set(vals), reverse=higher_is_better)
    return (vals_sorted[0] if vals_sorted else float("nan"),
            vals_sorted[1] if len(vals_sorted) > 1 else float("nan"))


def fmt_val(val, width, fmt_str, best, second):
    if np.isnan(val):
        return f"{'n/a':>{width}}"
    s = fmt_str.format(val)
    if not np.isnan(best) and val == best:
        s = BOLD + s + RESET
    elif not np.isnan(second) and val == second:
        s = UNDERLINE + s + RESET
    return f"{s:>{width}}"


LABEL_WIDTH = max(len("Experiment"), max(len(label) for _, label in EXPERIMENTS))

metrics_header = "  ".join(f"{hdr:>{w}}" for _, hdr, w, _ in METRICS)
metrics_width  = len(metrics_header)


def print_row(label, s, ranks, missing=False):
    if missing:
        print(f"  {label:<{LABEL_WIDTH}}  {'(no results)':>{metrics_width}}")
        return
    cells = []
    for key, _, width, hib in METRICS:
        best, second = ranks[key]
        fmt_str = "{:6.2f}" if key == "psnr" else \
                  "{:6.3f}" if key in ("ssim", "lpips") else \
                  "{:7.4f}" if key == "ate" else \
                  "{:6.1f}"
        cells.append(fmt_val(s[key], width, fmt_str, best, second))
    print(f"  {label:<{LABEL_WIDTH}}  " + "  ".join(cells))


col_header = f"  {'Experiment':<{LABEL_WIDTH}}  " + metrics_header
separator  = "  " + "-" * (len(col_header) - 2)

print(f"\nResults from: {results_dir}\n")

for dataset_label, tum_filter in [("TUM", True), ("Replica", False)]:
    all_stats = []
    for exp_name, _ in EXPERIMENTS:
        exp_dir  = os.path.join(results_dir, exp_name)
        log_path = os.path.join(exp_dir, "log.csv")
        if not os.path.exists(log_path):
            all_stats.append(None)
            continue
        rows   = load_log_csv(log_path)
        subset = [r for r in rows if is_tum(r[COL_SCENE]) == tum_filter]
        all_stats.append(compute_stats(subset, find_scene_dirs(exp_dir)) if subset else None)

    ranks = {key: rank_values(all_stats, key, hib) for key, _, _, hib in METRICS}

    print(f"=== {dataset_label} ===")
    print(col_header)
    print(separator)
    for (exp_name, label), s in zip(EXPERIMENTS, all_stats):
        print_row(label, s, ranks, missing=(s is None))
    print()
